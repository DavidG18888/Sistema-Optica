    private void btnCatalogoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCatalogoActionPerformed
        com.mycompany.sistemaoptica.dao.impl.ClienteDAO clienteDAO
                = new com.mycompany.sistemaoptica.dao.impl.ClienteDAO();

        int idCliente = clienteDAO.buscarIdClientePorUsuario(idUsuario);

        if (idCliente <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se encontró el registro del cliente.");
            return;
        }

        new Vista.FrmCatalogoAros(idCliente).setVisible(true);
        this.dispose();
    }//GEN-LAST:event_btnCatalogoActionPerformed

