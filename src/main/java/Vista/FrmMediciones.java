    private void RegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RegistrarActionPerformed

        try {
            com.mycompany.sistemaoptica.model.Medicion m
                    = new com.mycompany.sistemaoptica.model.Medicion();

            String idTexto = txtIdCliente.getText().trim();

            if (idTexto.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Ingrese el ID del cliente.");
                return;
            }

            int idCliente = Integer.parseInt(idTexto);
            m.setIdCliente(idCliente);

            String esfera = txtEsfera.getText().trim();
            String cilindro = txtCilindro.getText().trim();
            String eje = txtEje.getText().trim();
            String adicion = txtAdicion.getText().trim();

            m.setEsfera(esfera.isEmpty() ? null : Double.valueOf(esfera));
            m.setCilindro(cilindro.isEmpty() ? null : Double.valueOf(cilindro));
            m.setEje(eje.isEmpty() ? null : Integer.valueOf(eje));
            m.setAdicion(adicion.isEmpty() ? null : Double.valueOf(adicion));
            m.setObservaciones(txtObservaciones.getText().trim());

            com.mycompany.sistemaoptica.controller.MedicionController controller
                    = new com.mycompany.sistemaoptica.controller.MedicionController();

            if (controller.insertarMedicion(m)) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Medicion registrada correctamente.");

                txtEsfera.setText("");
                txtCilindro.setText("");
                txtEje.setText("");
                txtAdicion.setText("");
                txtObservaciones.setText("");

            } else {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "No se pudo registrar la medición y por ello verifique el ID del cliente y los valores ingresados.");
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Revise que esfera, cilindro y adición sean numeros decimales y que el eje sea un numero entero.");
        }

    }//GEN-LAST:event_RegistrarActionPerformed

    private void Consultar_historialActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Consultar_historialActionPerformed

        try {
            String idTexto = txtIdCliente.getText().trim();

            if (idTexto.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Ingrese el ID del cliente para consultar su historial.");
                return;
            }

            int idCliente = Integer.parseInt(idTexto);
            
            if (modoCliente) {
                idCliente = idClienteSesion;
            }

            com.mycompany.sistemaoptica.controller.MedicionController controller
                    = new com.mycompany.sistemaoptica.controller.MedicionController();

            java.util.ArrayList<com.mycompany.sistemaoptica.model.Medicion> lista
                    = controller.listarPorCliente(idCliente);

            javax.swing.table.DefaultTableModel modelo
                    = new javax.swing.table.DefaultTableModel();

            modelo.addColumn("ID Medicion");
            modelo.addColumn("ID Cliente");
            modelo.addColumn("Fecha");
            modelo.addColumn("Esfera");
            modelo.addColumn("Cilindro");
            modelo.addColumn("Eje");
            modelo.addColumn("Adición");
            modelo.addColumn("Observaciones");

            for (com.mycompany.sistemaoptica.model.Medicion m : lista) {
                modelo.addRow(new Object[]{
                    m.getIdMedicion(),
                    m.getIdCliente(),
                    m.getFecha(),
                    m.getEsfera(),
                    m.getCilindro(),
                    m.getEje(),
                    m.getAdicion(),
                    m.getObservaciones()
                });
            }

            jTable1.setModel(modelo);

            if (lista.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "No se encontraron mediciones para ese cliente.");
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "El ID del cliente debe ser un numero entero.");
        }

    }//GEN-LAST:event_Consultar_historialActionPerformed

