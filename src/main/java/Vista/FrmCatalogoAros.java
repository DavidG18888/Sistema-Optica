    private void btnFiltrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFiltrarActionPerformed
        try {
            String marca = cmbMarca.getSelectedItem().toString();
            String material = cmbMaterial.getSelectedItem().toString();
            String forma = cmbForma.getSelectedItem().toString();

            double precioMin = txtPrecioMin.getText().trim().isEmpty()
                    ? 0
                    : Double.parseDouble(txtPrecioMin.getText().trim());

            double precioMax = txtPrecioMax.getText().trim().isEmpty()
                    ? Double.MAX_VALUE
                    : Double.parseDouble(txtPrecioMax.getText().trim());

            if (precioMin < 0 || precioMax < 0 || precioMin > precioMax) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Verificá los precios ingresados.");
                return;
            }

            modeloTabla.setRowCount(0);

            ArrayList<Producto> productos =
                    productoController.listarProductos();

            for (Producto p : productos) {

                boolean coincideMarca = marca.equals("Todas")
                        || (p.getMarca() != null
                        && p.getMarca().equalsIgnoreCase(marca));

                boolean coincideMaterial = material.equals("Todos")
                        || (p.getMaterial() != null
                        && p.getMaterial().equalsIgnoreCase(material));

                boolean coincideForma = forma.equals("Todas")
                        || (p.getForma() != null
                        && p.getForma().equalsIgnoreCase(forma));

                boolean coincidePrecio = p.getPrecio() >= precioMin
                        && p.getPrecio() <= precioMax;

                if ("ARO".equalsIgnoreCase(p.getTipo())
                        && "ACTIVO".equalsIgnoreCase(p.getEstado()) && p.getStock() > 0 && coincideMarca && coincideMaterial
                        && coincideForma && coincidePrecio) {

                    modeloTabla.addRow(new Object[]{
                        p.getIdProducto(), p.getNombre(), p.getMarca(), p.getMaterial(), p.getForma(), p.getPrecio(), p.getStock()
                    });
                }
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ingresá precios válidos.");
        }
    }//GEN-LAST:event_btnFiltrarActionPerformed

