    private void btnApartarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnApartarActionPerformed
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Seleccioná un aro del catálogo.");
            return;
        }

        if (idCliente <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se identificó al cliente que inició sesión.");
            return;
        }

        int idProducto = Integer.parseInt(
                jTable1.getValueAt(fila, 0).toString());

        com.mycompany.sistemaoptica.model.Apartado apartado
                = new com.mycompany.sistemaoptica.model.Apartado(
                        idCliente, idProducto);

        boolean guardado = apartadoController.insertarApartado(apartado);

        if (guardado) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "El aro se apartó correctamente.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se pudo apartar el aro. Verificá que siga disponible.");
        }
    }//GEN-LAST:event_btnApartarActionPerformed

