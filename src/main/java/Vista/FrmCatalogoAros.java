    private void cargarFiltros() {

        cmbMarca.removeAllItems();
        cmbMaterial.removeAllItems();
        cmbForma.removeAllItems();

        cmbMarca.addItem("Todas");
        cmbMaterial.addItem("Todos");
        cmbForma.addItem("Todas");

        ArrayList<Producto> productos =
                productoController.listarProductos();

        for (Producto p : productos) {

            if ("ARO".equalsIgnoreCase(p.getTipo())
                    && "ACTIVO".equalsIgnoreCase(p.getEstado())
                    && p.getStock() > 0) {

                agregarSiNoExiste(cmbMarca, p.getMarca());
                agregarSiNoExiste(cmbMaterial, p.getMaterial());
                agregarSiNoExiste(cmbForma, p.getForma());
            }
        }
    }

    private void agregarSiNoExiste(
            javax.swing.JComboBox<String> combo, String valor) {

        if (valor == null || valor.trim().isEmpty()) {
            return;
        }

        for (int i = 0; i < combo.getItemCount(); i++) {
            if (combo.getItemAt(i).equalsIgnoreCase(valor)) {
                return;
            }
        }

        combo.addItem(valor);
    }

