    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed

        String correo = txtCorreo.getText().trim();
        String contrasena = new String(txtContrasena.getPassword());

        if (correo.isEmpty() || contrasena.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ingrese su correo y contraseña.");
            return;
        }

        com.mycompany.sistemaoptica.controller.UsuarioController controller
                = new com.mycompany.sistemaoptica.controller.UsuarioController();

        com.mycompany.sistemaoptica.model.Usuario usuario
                = controller.iniciarSesion(correo, contrasena);

        if (usuario == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Correo o contraseña incorrectos, o cuenta inactiva.");
            return;
        }


            if ("CLIENTE".equalsIgnoreCase(usuario.getRol())) {

                javax.swing.JOptionPane.showMessageDialog(this,
                        "Bienvenido al sistema.");

                new Vista.FrmMenuCliente(usuario.getIdUsuario()).setVisible(true);
                this.dispose();


            } else if ("VENDEDOR".equalsIgnoreCase(usuario.getRol())) {

                javax.swing.JOptionPane.showMessageDialog(this,
                        "Bienvenido al sistema.");

                new Vista.FrmMenuVendedor(usuario.getIdUsuario()).setVisible(true);
                this.dispose();

            } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "El rol de usuario no es válido.");
        }

    }//GEN-LAST:event_btnIngresarActionPerformed

