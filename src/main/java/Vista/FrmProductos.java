    private void cargarProductos() {

    com.mycompany.sistemaoptica.dao.impl.ProductoDAO dao
            = new com.mycompany.sistemaoptica.dao.impl.ProductoDAO();

    java.util.ArrayList<com.mycompany.sistemaoptica.model.Producto> lista
            = dao.listarProductos();

    javax.swing.table.DefaultTableModel modelo
            = new javax.swing.table.DefaultTableModel();

    modelo.addColumn("ID");
    modelo.addColumn("Nombre");
    modelo.addColumn("Tipo");
    modelo.addColumn("Marca");
    modelo.addColumn("Material");
    modelo.addColumn("Forma");
    modelo.addColumn("Precio");
    modelo.addColumn("Stock");
    modelo.addColumn("Estado");

    for (com.mycompany.sistemaoptica.model.Producto p : lista) {
        modelo.addRow(new Object[]{
            p.getIdProducto(),
            p.getNombre(),
            p.getTipo(),
            p.getMarca(),
            p.getMaterial(),
            p.getForma(),
            p.getPrecio(),
            p.getStock(),
            p.getEstado()
        });
    }

    jTable1.setModel(modelo);
    
    mostrarAlertaStockBajo();
}
    

    private void mostrarAlertaStockBajo() {

        StringBuilder mensaje = new StringBuilder();

        for (int i = 0; i < jTable1.getRowCount(); i++) {

            String tipo = jTable1.getValueAt(i, 2).toString();
            String nombre = jTable1.getValueAt(i, 1).toString();
            int stock = Integer.parseInt(
                    jTable1.getValueAt(i, 7).toString());

            if (tipo.equalsIgnoreCase("ARO") && stock < 5) {
                mensaje.append(nombre)
                        .append(" - Stock: ")
                        .append(stock)
                        .append("\n");
            }
        }

        if (mensaje.length() > 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "ALERTA: Aros con menos de 5 unidades:\n\n"
                    + mensaje,
                    "Stock bajo",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
        }
    }


