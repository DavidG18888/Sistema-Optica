    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

        int fila = jTable1.getSelectedRow();

        if (fila < 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Seleccione un producto de la tabla para eliminar.");
            return;
        }

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "¿Esta seguro de eliminar este producto?",
                "Confirmar eliminacion",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {

            int idProducto = Integer.parseInt(
                    jTable1.getValueAt(fila, 0).toString());

            com.mycompany.sistemaoptica.controller.ProductoController controller
                    = new com.mycompany.sistemaoptica.controller.ProductoController();

            if (controller.eliminarProducto(idProducto)) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Producto eliminado correctamente.");
                cargarProductos();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "No se pudo eliminar el producto.");
            }
        }

    }//GEN-LAST:event_jButton3ActionPerformed

