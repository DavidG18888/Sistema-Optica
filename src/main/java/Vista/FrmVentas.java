    private void cargarProductos() {
        productos = productoDAO.listarProductos();

        cmbProductos.removeAllItems();

        for (Producto p : productos) {
            if ("ACTIVO".equalsIgnoreCase(p.getEstado())
                    && p.getStock() > 0) {

                cmbProductos.addItem(p.toString());
            }
        }
    }
    
