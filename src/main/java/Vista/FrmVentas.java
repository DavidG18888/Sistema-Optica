    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String seleccionado = (String) cmbProductos.getSelectedItem();

        if (seleccionado == null) {
            JOptionPane.showMessageDialog(this, "Seleccioná un producto.");
            return;
        }

        int cantidad;

        try {
            cantidad = Integer.parseInt(txtCantidad.getText().trim());

            if (cantidad <= 0) {
                JOptionPane.showMessageDialog(this,
                        "La cantidad debe ser mayor que cero.");
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Ingresá una cantidad válida.");
            return;
        }

        Producto productoSeleccionado = null;

        for (Producto p : productos) {
            if (seleccionado.equals(p.toString())) {
                productoSeleccionado = p;
                break;
            }
        }

        if (productoSeleccionado == null) {
            JOptionPane.showMessageDialog(this,
                    "No se encontró el producto seleccionado.");
            return;
        }

        int cantidadEnTabla = 0;

        for (int i = 0; i < modeloTabla.getRowCount(); i++) {
            if ((int) modeloTabla.getValueAt(i, 0)
                    == productoSeleccionado.getIdProducto()) {
                cantidadEnTabla += (int) modeloTabla.getValueAt(i, 2);
            }
        }

        if (cantidadEnTabla + cantidad > productoSeleccionado.getStock()) {
            JOptionPane.showMessageDialog(this,
                    "No hay suficiente stock disponible.");
            return;
        }

        double precio = productoSeleccionado.getPrecio();
        double importe = precio * cantidad;

        modeloTabla.addRow(new Object[]{
            productoSeleccionado.getIdProducto(),
            productoSeleccionado.getNombre(),
            cantidad,
            String.format("L. %.2f", precio),
            importe
        });

        actualizarTotales();
        txtCantidad.setText("");
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnRegistrarVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarVentaActionPerformed
        if (modeloTabla.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this,
                    "Agregá al menos un producto a la venta.");
            return;
        }

        int idCliente;
        int idMedicion;
        int idVendedor;

        try {
            idCliente = Integer.parseInt(txtIdCliente.getText().trim());
            idMedicion = Integer.parseInt(txtIdMedicion.getText().trim());
            idVendedor = this.idVendedor;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Ingresá correctamente los ID del cliente, medición y vendedor.");
            return;
        }

        BigDecimal subtotalVenta = BigDecimal.valueOf(subtotal).setScale(2,
                java.math.RoundingMode.HALF_UP);

        BigDecimal impuestoVenta = BigDecimal.valueOf(subtotal * 0.15).setScale(2,
                java.math.RoundingMode.HALF_UP);

        BigDecimal totalVenta = subtotalVenta.add(impuestoVenta);

        Venta venta = new Venta();
        venta.setIdCliente(idCliente);
        venta.setIdMedicion(idMedicion);
        venta.setIdVendedor(idVendedor);
        venta.setFecha(new Date());
        venta.setSubtotal(subtotalVenta);
        venta.setImpuesto(impuestoVenta);
        venta.setTotal(totalVenta);

        ArrayList<DetalleVenta> detalles = new ArrayList<>();

        for (int i = 0; i < modeloTabla.getRowCount(); i++) {
            DetalleVenta detalle = new DetalleVenta();

            detalle.setIdProducto((int) modeloTabla.getValueAt(i, 0));
            detalle.setCantidad((int) modeloTabla.getValueAt(i, 2));

            int idProducto = (int) modeloTabla.getValueAt(i, 0);
            Producto producto = productos.stream()
                    .filter(p -> p.getIdProducto() == idProducto)
                    .findFirst()
                    .orElse(null);

            if (producto == null) {
                JOptionPane.showMessageDialog(this,
                        "No se encontró el producto de la venta.");
                return;
            }

            double precio = producto.getPrecio();

            detalle.setPrecioUnitario(
                    BigDecimal.valueOf(precio).setScale(2,
                            java.math.RoundingMode.HALF_UP));

            detalle.setSubtotal(
                    BigDecimal.valueOf(precio * detalle.getCantidad()).setScale(2,
                            java.math.RoundingMode.HALF_UP));

            detalle.setPrecioUnitario(BigDecimal.valueOf(precio).setScale(2,
                    java.math.RoundingMode.HALF_UP));

            detalle.setSubtotal(BigDecimal.valueOf(
                    precio * detalle.getCantidad()).setScale(2,
                    java.math.RoundingMode.HALF_UP));

            detalles.add(detalle);
        }

        boolean registrada = ventaController.registrarVenta(venta, detalles);

        if (registrada) {
            JOptionPane.showMessageDialog(this,
                    "Venta registrada correctamente.");

            modeloTabla.setRowCount(0);
            actualizarTotales();
            cargarProductos();

            txtIdCliente.setText("");
            txtIdMedicion.setText("");
            txtIdVendedor.setText("");
            txtCantidad.setText("");
        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo registrar la venta. Verificá los ID, "
                    + "la medición y el inventario disponible.");
        }
    }//GEN-LAST:event_btnRegistrarVentaActionPerformed

    private void actualizarTotales() {
        subtotal = 0;

        for (int i = 0; i < modeloTabla.getRowCount(); i++) {
            subtotal += Double.parseDouble(
                    modeloTabla.getValueAt(i, 4).toString());
        }

        double impuesto = subtotal * 0.15;
        double total = subtotal + impuesto;

        lblSubtotal.setText(String.format("L. %.2f", subtotal));
        lblImpuesto.setText(String.format("L. %.2f", impuesto));
        lblTotal.setText(String.format("L. %.2f", total));
    }
